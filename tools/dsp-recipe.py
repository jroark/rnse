"""From a --trace-dsp log and the flash image: the recipe by which the stock driver's
download to a card processor is rebuilt from the flash (flash runs, zero runs, a few
literal header words, and where the driver reads an answer).  Verifies itself."""
import sys,re,struct
fl=open(sys.argv[2],'rb').read()
ops=[]
for l in open(sys.argv[1],errors='replace'):
    m=re.match(r'\[dsp0\] host ([WR]) (\w+)',l)
    if m: ops.append((m.group(1),int(m.group(2),16)))
# the download ends with the first message (1202 ...)
nw=0; end=None
for i,(k,v) in enumerate(ops):
    if k=='W':
        if v==0x1202 and nw>20000: end=i; break
        nw+=1
ops=ops[:end]
W=[v for k,v in ops if k=='W']
reads=[]; n=0
for k,v in ops:
    if k=='W': n+=1
    else: reads.append(n)
print('download: %d words, answers read after %s'%(len(W),reads), file=sys.stderr)
rec=[]  # (kind, a, n): 'F' flash addr, 'Z' zeros, 'L' literal index, 'R'
lits=[]
i=0
def flush_reads():
    while reads and reads[0]==i:
        rec.append(('R',0,0)); reads.pop(0)
while i<len(W):
    flush_reads()
    limit=min([r for r in reads if r>i]+[len(W)])
    # zeros
    n=0
    while i+n<limit and W[i+n]==0: n+=1
    if n>=8:
        rec.append(('Z',0,n)); i+=n; continue
    pat=b''.join(struct.pack('<H',v) for v in W[i:i+8])
    at=fl.find(pat,0x200000,0x20f000) if i+8<=limit else -1
    if at>=0:
        n=8
        while i+n<limit and fl[at+2*n:at+2*n+2]==struct.pack('<H',W[i+n]): n+=1
        rec.append(('F',at,n)); i+=n; continue
    if rec and rec[-1][0]=='L':
        k,a,n=rec[-1]; rec[-1]=('L',a,n+1)
    else:
        rec.append(('L',len(lits),1))
    lits.append(W[i]); i+=1
flush_reads()
# verify
out=[]; rd=[]
for k,a,n in rec:
    if k=='F': out+=[struct.unpack_from('<H',fl,a+2*j)[0] for j in range(n)]
    elif k=='Z': out+=[0]*n
    elif k=='L': out+=lits[a:a+n]
    else: rd.append(len(out))
assert out==W, 'recipe does not rebuild the stream'
print('recipe: %d steps, %d literal words; rebuilds the stream exactly'%(len(rec),len(lits)), file=sys.stderr)
print('/* Generated by the recipe tool from a trace of the stock driver; see sd192.c. */')
print('static const u16 literal[] = { %s };'%', '.join('0x%04x'%v for v in lits))
print('static const struct step { u8 kind; u32 at; u16 count; } recipe[] = {')
for k,a,n in rec:
    print('    { %s, 0x%06x, %d },'%({'F':'FROM_FLASH','Z':'ZEROES','L':'LITERAL','R':'ANSWER'}[k],a,n))
print('};')
